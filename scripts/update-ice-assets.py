"""Validate the five approved files and refresh URL versions; never modify images."""
import hashlib
import json
from pathlib import Path

root=Path(__file__).resolve().parents[1]
manifest=json.loads((root/'ICE-ASSETS.json').read_text())
expected={f'dist/assets/ice-{i}.webp' for i in range(5)}
if manifest.get('status')!='user-approved' or {f['path'] for f in manifest['files']}!=expected:
    raise SystemExit('Expected the five user-approved ice forms')
versions={}
for item in manifest['files']:
    data=(root/item['path']).read_bytes()
    blob_sha=hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()
    if len(data)!=item['size'] or blob_sha!=item['sha']:
        raise SystemExit('Approved image mismatch: '+item['path'])
    versions[item['path'].removeprefix('dist/')]=blob_sha
code='''/* Generated by scripts/update-ice-assets.py from ICE-ASSETS.json.
   Only URLs are versioned; approved image bytes are never changed. */
(function(root){'use strict';
const versions=Object.freeze(VERSIONS);
function url(path){return versions[path]?path+'?v='+versions[path]:path;}
root.ForestArt=Object.freeze({url,versions});
})(globalThis);
'''.replace('VERSIONS',json.dumps(versions,ensure_ascii=False,indent=2))
(root/'dist/asset-urls.js').write_text(code)
print('Validated all five approved Git blob hashes and byte sizes; refreshed shared URLs')
